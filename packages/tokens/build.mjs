#!/usr/bin/env node
// Builds every token output from src/tokens.json (the single source of truth).
//
//   dist/tokens.css         CSS variables (primitives + semantic, light + dark)
//   dist/tailwind.css       tokens.css + Tailwind v4 `@theme inline` mapping
//   dist/fonts.css          Google Fonts import (optional, for non-Next.js apps)
//   dist/index.js / .d.ts   resolved tokens as a JS object
//   dist/shadcn-theme.json  `cssVars` for the shadcn registry theme item
//   lwc/mintelTokens/       Salesforce LWC CSS-only module (`@import 'c/mintelTokens';`)
//   salesforce/mintel-global.css  page-level CSS (static resource / LWR head) + SLDS styling hooks
//
// No dependencies on purpose — run with `node build.mjs`.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = dirname(fileURLToPath(import.meta.url))
const src = JSON.parse(readFileSync(join(root, "src/tokens.json"), "utf8"))
const MODE_EXT = "tech.m-intelligence.modes"
const HEADER = "/* Generated by @mintelligence-dev/tokens — do not edit. Source: src/tokens.json */\n"

// ---------- resolve ----------
function lookup(path) {
  let node = src
  for (const part of path.split(".")) {
    node = node?.[part]
    if (node === undefined) throw new Error(`Unknown token reference {${path}}`)
  }
  if (!("$value" in node)) throw new Error(`{${path}} is a group, not a token`)
  return resolve(node.$value)
}
function resolve(value) {
  if (typeof value === "string") {
    const m = value.match(/^\{(.+)\}$/)
    return m ? lookup(m[1]) : value
  }
  return value
}
const refName = (value) => {
  // "{color.blue.600}" -> "--mintel-color-blue-600" so semantic vars point at primitives
  const m = typeof value === "string" && value.match(/^\{(.+)\}$/)
  return m ? `--mintel-${m[1].replaceAll(".", "-")}` : null
}

// primitives
const primitives = [] // [cssName, value]
for (const [family, scale] of Object.entries(src.color)) {
  for (const [step, tok] of Object.entries(scale)) {
    if (step.startsWith("$")) continue
    primitives.push([`--mintel-color-${family}-${step}`, resolve(tok.$value)])
  }
}

// semantic (light/dark)
const semantic = Object.entries(src.semantic).map(([name, tok]) => {
  const light = tok.$value
  const dark = tok.$extensions?.[MODE_EXT]?.dark ?? light
  return {
    name,
    light: { ref: refName(light), value: resolve(light) },
    dark: { ref: refName(dark), value: resolve(dark) },
  }
})

const fontStack = (key) =>
  src.font[key].$value.map((f) => (/[\s]/.test(f) && !f.startsWith("ui-") ? `"${f}"` : f)).join(", ")
const fonts = { sans: fontStack("sans"), heading: fontStack("heading"), mono: fontStack("mono") }
const radius = src.radius.base.$value

// ---------- helpers ----------
const out = (rel, text) => {
  const file = join(root, rel)
  mkdirSync(dirname(file), { recursive: true })
  writeFileSync(file, text)
  console.log("  wrote", rel)
}
const block = (selector, lines) => `${selector} {\n${lines.map((l) => `  ${l}`).join("\n")}\n}\n`
const v = (entry, prefix = "") => (entry.ref ? `var(${entry.ref})` : entry.value)

// ---------- dist/tokens.css ----------
const commonVars = [
  ...primitives.map(([n, val]) => `${n}: ${val};`),
  `--mintel-font-sans: ${fonts.sans};`,
  `--mintel-font-heading: ${fonts.heading};`,
  `--mintel-font-mono: ${fonts.mono};`,
  `--mintel-radius: ${radius};`,
]
const lightSemantic = semantic.map((s) => `--${s.name}: ${v(s.light)};`)
const darkSemantic = semantic.map((s) => `--${s.name}: ${v(s.dark)};`)
const extras = [
  `--radius: var(--mintel-radius);`,
  `--brand-gradient: linear-gradient(135deg, var(--brand) 0%, var(--brand-accent) 100%);`,
]
const DARK_SELECTOR = `.dark,\n[data-theme="dark"]`

out(
  "dist/tokens.css",
  HEADER +
    block(":root", [...commonVars, ...lightSemantic, ...extras]) +
    "\n" +
    block(DARK_SELECTOR, [...darkSemantic, "color-scheme: dark;"])
)

// ---------- dist/tailwind.css ----------
const themeLines = [
  ...semantic.map((s) => `--color-${s.name}: var(--${s.name});`),
  ...Object.keys(src.color).flatMap((family) =>
    Object.keys(src.color[family])
      .filter((k) => !k.startsWith("$"))
      .map((step) => `--color-mintel-${family}-${step}: var(--mintel-color-${family}-${step});`)
  ),
  `--font-sans: var(--mintel-font-sans);`,
  `--font-heading: var(--mintel-font-heading);`,
  `--font-mono: var(--mintel-font-mono);`,
  `--radius-sm: calc(var(--radius) - 4px);`,
  `--radius-md: calc(var(--radius) - 2px);`,
  `--radius-lg: var(--radius);`,
  `--radius-xl: calc(var(--radius) + 4px);`,
  `--radius-2xl: calc(var(--radius) + 8px);`,
]
out(
  "dist/tailwind.css",
  HEADER +
    `/* Usage (Tailwind v4):  @import "tailwindcss";  @import "@mintelligence-dev/tokens/tailwind.css"; */\n` +
    `@import "./tokens.css";\n\n` +
    `@custom-variant dark (&:where(.dark, .dark *, [data-theme="dark"], [data-theme="dark"] *));\n\n` +
    block("@theme inline", themeLines) +
    "\n" +
    `@layer base {\n  * {\n    @apply border-border outline-ring/50;\n  }\n  body {\n    @apply bg-background text-foreground font-sans antialiased;\n  }\n}\n`
)

// ---------- dist/fonts.css ----------
out(
  "dist/fonts.css",
  HEADER +
    `/* Optional: loads brand fonts from Google Fonts. Next.js apps should prefer next/font. */\n` +
    `@import url("https://fonts.googleapis.com/css2?family=IBM+Plex+Sans+Thai:wght@400;500;600;700&family=Manrope:wght@400;500;600;700;800&family=Rubik:wght@500;600;700&family=JetBrains+Mono:wght@400;500&display=swap");\n`
)

// ---------- dist/index.js + .d.ts ----------
const jsTokens = {
  color: Object.fromEntries(
    Object.entries(src.color).map(([family, scale]) => [
      family,
      Object.fromEntries(
        Object.entries(scale)
          .filter(([k]) => !k.startsWith("$"))
          .map(([k, t]) => [k, resolve(t.$value)])
      ),
    ])
  ),
  light: Object.fromEntries(semantic.map((s) => [s.name, s.light.value])),
  dark: Object.fromEntries(semantic.map((s) => [s.name, s.dark.value])),
  font: fonts,
  radius,
}
out("dist/index.js", `${HEADER}export const tokens = ${JSON.stringify(jsTokens, null, 2)}\nexport default tokens\n`)
out(
  "dist/index.d.ts",
  `${HEADER}export type SemanticToken = ${semantic.map((s) => JSON.stringify(s.name)).join(" | ")}\n` +
    `export interface MintelTokens {\n  color: Record<${Object.keys(src.color)
      .map((k) => JSON.stringify(k))
      .join(" | ")}, Record<string, string>>\n  light: Record<SemanticToken, string>\n  dark: Record<SemanticToken, string>\n  font: { sans: string; heading: string; mono: string }\n  radius: string\n}\nexport declare const tokens: MintelTokens\nexport default tokens\n`
)

// ---------- dist/shadcn-theme.json ----------
// Registry cssVars must be self-contained (consumers don't have the primitives), so use resolved values.
out(
  "dist/shadcn-theme.json",
  JSON.stringify(
    {
      theme: {
        "font-sans": fonts.sans,
        "font-heading": fonts.heading,
        "font-mono": fonts.mono,
        "color-brand": "var(--brand)",
        "color-brand-foreground": "var(--brand-foreground)",
        "color-brand-accent": "var(--brand-accent)",
        "color-brand-accent-foreground": "var(--brand-accent-foreground)",
        "color-brand-cyan": "var(--brand-cyan)",
        "color-success": "var(--success)",
        "color-warning": "var(--warning)",
        "color-info": "var(--info)",
      },
      light: {
        radius,
        ...Object.fromEntries(semantic.map((s) => [s.name, s.light.value])),
      },
      dark: Object.fromEntries(semantic.map((s) => [s.name, s.dark.value])),
    },
    null,
    2
  ) + "\n"
)

// ---------- Salesforce: LWC CSS-only module ----------
// LWC component CSS is scoped to the component, so variables live on :host and every
// name is prefixed --mintel-* to avoid clashing with SLDS / --lwc-* tokens.
const lwcLight = semantic.map((s) => `--mintel-${s.name}: ${v(s.light)};`)
const lwcDark = semantic.map((s) => `--mintel-${s.name}: ${v(s.dark)};`)
const lwcExtras = [
  `--mintel-brand-gradient: linear-gradient(135deg, var(--mintel-brand) 0%, var(--mintel-brand-accent) 100%);`,
]
out(
  "lwc/mintelTokens/mintelTokens.css",
  HEADER +
    `/* In a component's CSS:  @import 'c/mintelTokens';  then use var(--mintel-primary) etc.\n   Dark mode: add class="mintel-dark" (or data-theme="dark") on the host element. */\n` +
    block(":host", [...commonVars, ...lwcLight, ...lwcExtras]) +
    "\n" +
    block(`:host(.mintel-dark),\n:host([data-theme="dark"])`, lwcDark)
)
out(
  "lwc/mintelTokens/mintelTokens.js-meta.xml",
  `<?xml version="1.0" encoding="UTF-8"?>\n<!-- CSS-only module generated by @mintelligence-dev/tokens -->\n<LightningComponentBundle xmlns="http://soap.sforce.com/2006/04/metadata">\n    <apiVersion>62.0</apiVersion>\n    <isExposed>false</isExposed>\n</LightningComponentBundle>\n`
)

// ---------- Salesforce: global CSS + SLDS styling hooks ----------
const L = Object.fromEntries(semantic.map((s) => [s.name, `var(--mintel-${s.name})`]))
const sldsHooks = [
  "/* SLDS component styling hooks: rebrand base lightning-* components */",
  `--slds-c-button-brand-color-background: ${L.primary};`,
  `--slds-c-button-brand-color-border: ${L.primary};`,
  `--slds-c-button-brand-text-color: ${L["primary-foreground"]};`,
  `--slds-c-button-brand-color-background-hover: var(--mintel-color-blue-700);`,
  `--slds-c-button-brand-color-border-hover: var(--mintel-color-blue-700);`,
  `--slds-c-button-brand-color-background-active: var(--mintel-color-blue-800);`,
  `--slds-c-button-brand-text-color-hover: ${L["primary-foreground"]};`,
  `--slds-c-button-radius-border: var(--mintel-radius);`,
  "/* SLDS 2 (Cosmos) global hooks */",
  `--slds-g-color-accent-1: ${L.primary};`,
  `--slds-g-color-accent-2: var(--mintel-color-blue-700);`,
  `--slds-g-color-accent-container-1: ${L.primary};`,
  `--slds-g-color-on-accent-1: ${L["primary-foreground"]};`,
  `--slds-g-color-border-accent-1: ${L.primary};`,
]
out(
  "salesforce/mintel-global.css",
  HEADER +
    `/* Page-level stylesheet: upload as a Static Resource and load with loadStyle(), or add to the\n   Experience Cloud (LWR) head markup. Hook names follow SLDS docs — verify against your org's SLDS version. */\n` +
    block(":root", [...commonVars, ...lwcLight, ...lwcExtras, ...sldsHooks]) +
    "\n" +
    block(`.mintel-dark,\n[data-theme="dark"]`, lwcDark)
)

console.log(`✓ ${primitives.length} primitives, ${semantic.length} semantic tokens`)
