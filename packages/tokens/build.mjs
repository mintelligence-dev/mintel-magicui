out(
  "salesforce/mintel-global.css",
  HEADER +
    `/* Page-level stylesheet: upload as a Static Resource and load with loadStyle(), or add to the\n   Experience Cloud (LWR) head markup. Hook names are checked against the SLDS 1 CSS; SLDS 2-only hooks are marked. */\n` +
    block(":root", [...commonVars, ...lwcLight, ...lwcExtras, ...sldsHooks]) +
    "\n" +
    block(`.mintel-dark,\n[data-theme="dark"]`, lwcDark)
)

// ---------- Salesforce SFDX project (packages/salesforce): same generated files, deployable as-is ----------
const sfdx = "../salesforce/force-app/main/default"
for (const f of ["mintelTokens.css", "mintelTokens.js-meta.xml"]) {
  out(`${sfdx}/lwc/mintelTokens/${f}`, readFileSync(join(root, "lwc/mintelTokens", f), "utf8"))
}
out(`${sfdx}/staticresources/mintelGlobal.css`, readFileSync(join(root, "salesforce/mintel-global.css"), "utf8"))
out(
  `${sfdx}/staticresources/mintelGlobal.resource-meta.xml`,
  `<?xml version="1.0" encoding="UTF-8"?>\n<StaticResource xmlns="http://soap.sforce.com/2006/04/metadata">\n    <cacheControl>Public</cacheControl>\n    <contentType>text/css</contentType>\n    <description>Mintel UI brand stylesheet: CSS variables and SLDS styling hooks (generated by @mintelligence-dev/tokens)</description>\n</StaticResource>\n`
)

console.log(`✓ ${primitives.length} primitives, ${semantic.length} semantic tokens`)
